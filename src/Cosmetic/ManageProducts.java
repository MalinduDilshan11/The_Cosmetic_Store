    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try{
            String PID = txtPID.getText();
            String PName = txtPName.getText();
            String priceText = txtPrice.getText();
            String stockText = txtStock.getText();
            String Cat = txtCat.getText();
            
            if (PID.isEmpty() || PName.isEmpty() || priceText.isEmpty() || stockText.isEmpty() || Cat.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please fill in all the required fields before updating", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            double Price = Double.parseDouble(priceText);
            int Stock = Integer.parseInt(stockText);

            String sql = "UPDATE tblproducts SET Product_Name=? ,Price=? ,Stock=? ,Category=? WHERE Product_ID = ?";
            ps = con.prepareStatement(sql);

            ps.setString(1, PName);
            ps.setDouble(2, Price);
            ps.setInt(3, Stock);
            ps.setString(4, Cat);
            ps.setString(5, PID);
            
            if(ps.executeUpdate()>0){
                JOptionPane.showMessageDialog(this, "The Product Details Updated!");
            } else{
                JOptionPane.showMessageDialog(this, "This Product Not Added!");
            }
               
        }catch(Exception e){
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

