    private void btnInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertActionPerformed
        try {
            String PID = txtPID.getText();
            String PName = txtPName.getText();
            String priceText = txtPrice.getText();
            String stockText = txtStock.getText();
            String Cat = txtCat.getText();

            if (PID.isEmpty() || PName.isEmpty() || priceText.isEmpty() || stockText.isEmpty() || Cat.isEmpty()) {
                JOptionPane.showMessageDialog(this, "All Fields are Required", "Error", JOptionPane.ERROR_MESSAGE);
                return;

            }
            
            double Price = Double.parseDouble(priceText);
            int Stock = Integer.parseInt(stockText);
     
            String sql = "INSERT INTO tblproducts VALUES (?,?,?,?,?)";
            ps = con.prepareStatement(sql);
            
            ps.setString(1, PID);
            ps.setString(2, PName);
            ps.setDouble(3, Price);
            ps.setInt(4, Stock);
            ps.setString(5, Cat);
            
            if (ps.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "The Procuct Details Inserted!");
                clear();
            }   
        }catch(Exception e){
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnInsertActionPerformed

